import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {workflowContexts} from '../src/leadMagnets/model.js';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.CHECK_ORIGIN || 'http://127.0.0.1:4173';
const output = process.env.QA_OUTPUT || 'output/playwright/scorecard';
await mkdir(output, {recursive: true});
const browser = await chromium.launch({headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const route = '/resources/workflow-bottleneck-scorecard';
try {
  for (const width of [1440, 390, 320]) {
    const context = await browser.newContext({viewport: {width, height: 844}, reducedMotion: 'reduce'});
    const page = await context.newPage();
    const errors = [], posts = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {if(request.method() === 'POST') posts.push(request.url());});
    const advance = () => page.getByRole('button', {name: 'Continue Assessment', exact: true}).click();
    const result = () => page.getByRole('button', {name: 'See My Result', exact: true}).click();
    for (const [key, value] of Object.entries(workflowContexts)) {
      await page.goto(origin + route + '?workflow=' + key);
      assert.equal(await page.locator('#lm-workflow').inputValue(), value);
      await page.locator('#lm-workflow').selectOption('Another administrative workflow');
      assert.equal(await page.locator('#lm-workflow').inputValue(), 'Another administrative workflow');
    }
    await page.goto(origin + route + '?workflow=unknown&effort=5');
    await advance();
    assert.equal(await page.locator('form').evaluate(form => form.checkValidity()), false);
    await page.goto(origin + route + '?workflow=reporting');
    await page.evaluate(() => document.fonts.ready);
    const field = await page.locator('#lm-workflow').boundingBox();
    assert.ok(field.y + field.height < 844, `First answer below viewport at ${width}: ${field.y}`);
    await page.screenshot({path: `${output}/${width}-scorecard-entry.png`, fullPage: true});
    await page.locator('#lm-workflow').focus();
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Download the Excel Workbook');
    await page.keyboard.press('Tab');
    assert.match(await page.evaluate(() => document.activeElement.textContent), /Continue Assessment/);
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'scorecard-start');
    assert.ok(Math.abs((await page.locator('#scorecard-start').boundingBox()).y - 110) < 3, 'Continue lands at the next question panel');
    await advance();
    assert.equal(await page.locator('form').evaluate(form => form.checkValidity()), false);
    for (const key of ['frequency', 'effort', 'handoffs', 'delay', 'rework', 'visibility']) await page.locator('#lm-' + key).selectOption('1');
    await advance();
    await page.locator('#lm-feasibility').selectOption('5');
    await page.locator('#lm-evidence').selectOption('5');
    await result();
    assert.equal(await page.locator('.lm-result').count(), 0);
    await page.locator('input[name="control"][value="No"]').check();
    await result();
    assert.match(await page.locator('.lm-signals').innerText(), /No clear bottleneck/);
    assert.equal(await page.locator('.lm-signals li').count(), 6);
    assert.ok(await page.getByRole('heading', {name: 'Simplify and keep watching'}).isVisible());
    await page.screenshot({path: `${output}/${width}-scorecard-low-result.png`, fullPage: true});
    await page.getByRole('link', {name: 'Discuss My Result'}).click();
    assert.ok(await page.locator('[name="includeSummary"]').isChecked());
    await page.goBack();
    assert.ok(await page.getByRole('heading', {name: 'Simplify and keep watching'}).isVisible());
    await page.getByRole('button', {name: 'Edit my answers'}).click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'scorecard-start');
    assert.ok(Math.abs((await page.locator('#scorecard-start').boundingBox()).y - 110) < 3, 'Edit lands at the retained workflow panel');
    assert.equal(await page.locator('#lm-workflow').inputValue(), 'Operational reporting');
    await advance();
    assert.equal(await page.locator('#lm-effort').inputValue(), '1');
    for (const key of ['frequency', 'effort', 'handoffs', 'delay', 'rework', 'visibility']) await page.locator('#lm-' + key).selectOption('5');
    await advance();
    await page.locator('#lm-evidence').selectOption('1');
    await result();
    assert.ok(await page.getByRole('heading', {name: 'Gather better evidence first'}).isVisible());
    await page.getByRole('button', {name: 'Edit my answers'}).click();
    await advance(); await advance();
    await page.locator('#lm-evidence').selectOption('5');
    await page.locator('#lm-feasibility').selectOption('1');
    await result();
    assert.ok(await page.getByRole('heading', {name: 'Clarify the boundary and feasibility'}).isVisible());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    assert.deepEqual(posts, []);
    assert.deepEqual(errors, []);
    await page.reload();
    assert.equal(await page.locator('#lm-workflow').inputValue(), 'Operational reporting');
    await advance();
    assert.equal(await page.locator('#lm-effort').inputValue(), '', 'Reload clears answers');
    await context.close();
  }
  console.log('PASS: four allowlisted entries, editable selection, ignored unknown context, keyboard navigation, mobile first question, required answers, low/evidence/feasibility branches, contact-back recovery, edit retention, no storage or submission, reload clearing.');
} finally {await browser.close();}
