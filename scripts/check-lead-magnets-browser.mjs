import assert from 'node:assert/strict';
import {mkdir, readFile} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.CHECK_ORIGIN || 'http://127.0.0.1:4173';
const output = process.env.QA_OUTPUT || '/private/tmp/heutrix-interactive-qa';
await mkdir(output, {recursive: true});
const browser = await chromium.launch({headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const errors = [];
const posts = [];
const ids = ['workflow-bottleneck-scorecard', 'enquiry-to-service-start-starter-kit', 'ai-guardrails-staff-starter-pack'];
try {
  for (const width of [1440, 390]) {
    const context = await browser.newContext({viewport: {width, height: 1000}, acceptDownloads: true});
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => {if (message.type() === 'error' && !message.location().url.endsWith('/api/requests')) errors.push(message.text());});
    page.on('request', request => {if (request.method() === 'POST') posts.push(request.url());});
    async function shot(name) {
      await page.evaluate(() => {window.scrollTo({top: 0, behavior: 'instant'}); return document.fonts.ready;});
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${name} overflows at ${width}`);
      await page.screenshot({path: `${output}/${width}-${name}.png`, fullPage: true});
    }
    async function choices(values) {for (const [name, value] of Object.entries(values)) await page.locator(`input[name="${name}"][value="${value}"]`).check();}
    await page.goto(origin + '/');
    assert.ok(await page.locator('a[href="/resources/workflow-bottleneck-scorecard"]').count() >= 1, 'Homepage must lead into an interactive tool');
    await page.goto(origin + '/resources');
    assert.equal(await page.getByRole('link', {name: 'Start the tool', exact: true}).count(), 3);
    assert.equal(await page.locator('a[download]').count(), 6);
    await shot('resources');
    await page.getByRole('link', {name: 'Start the tool', exact: true}).first().click();
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    assert.equal(await page.locator('form').evaluate(form => form.checkValidity()), false);
    assert.equal(await page.locator('.lm-progress [aria-current]').innerText(), '1\nChoose the workflow');
    await page.locator('#lm-workflow').selectOption('Worker onboarding');
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    for (const key of ['frequency', 'effort', 'handoffs', 'delay', 'rework', 'visibility']) await page.locator(`#lm-${key}`).selectOption('5');
    await shot('workflow-questions');
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    await page.locator('#lm-feasibility').selectOption('5');
    await page.locator('#lm-evidence').selectOption('5');
    await choices({control: 'No'});
    await page.getByRole('button', {name: 'See my result'}).click();
    assert.equal((await page.locator('.lm-score strong').innerText()).replace(/\s/g, ''), '100/100');
    assert.ok(await page.getByRole('heading', {name: 'Explore a bounded workflow improvement'}).isVisible());
    await shot('workflow-result');
    const downloaded = page.waitForEvent('download');
    await page.getByRole('button', {name: 'Save my action plan'}).click();
    const download = await downloaded;
    assert.match(await readFile(await download.path(), 'utf8'), /Prioritisation score: 100/);
    await page.getByRole('button', {name: 'Edit my answers'}).click();
    assert.equal(await page.locator('#lm-workflow').inputValue(), 'Worker onboarding');
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    assert.equal(await page.locator('#lm-frequency').inputValue(), '5');
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    await choices({control: 'Unsure'});
    await page.getByRole('button', {name: 'See my result'}).click();
    assert.ok(await page.getByRole('heading', {name: 'Resolve the control questions first'}).isVisible());
    await page.getByRole('link', {name: 'Discuss my result'}).click();
    assert.equal(await page.locator('#enquiry-service').inputValue(), 'heutrix-diagnostics');
    assert.ok(await page.locator('[name="includeSummary"]').isChecked());
    for (const [name, value] of Object.entries({name: 'Synthetic User', email: 'synthetic@example.com', organisation: 'Example Organisation', role: 'Operations lead', message: 'Synthetic workflow discussion for testing.'})) await page.locator(`#enquiry-${name}`).fill(value);
    for (const [name, value] of Object.entries({sector: 'Disability support provider', workflowSize: '4–6', timing: 'Within 1–3 months', decisionContext: 'I can approve a paid next step'})) await page.locator(`#enquiry-${name}`).selectOption(value);
    await page.locator('[name="safeInformation"]').check();
    await page.locator('[name="contactPermission"]').check();
    await shot('consultation-form');
    await page.getByRole('button', {name: 'Review my enquiry'}).click();
    assert.match(await page.locator('#enquiry-draft').inputValue(), /Resolve the control questions first/);
    assert.ok(await page.getByText('Nothing has been sent to Heutrix yet.', {exact: false}).isVisible());
    assert.ok(!(await page.locator('body').innerText()).includes('We have received'));
    await shot('enquiry-review');
    const submitted = page.waitForRequest(request => request.url().endsWith('/api/requests') && request.method() === 'POST');
    await page.getByRole('button', {name: 'Submit test request'}).click();
    assert.match((await submitted).postDataJSON().assessment.summary, /Resolve the control questions first/);
    await page.getByRole('heading', {name: 'Test request complete.'}).waitFor();
    assert.match(await page.locator('.lm-reference').innerText(), /^DEMO-/);
    const confirmationBox = await page.getByRole('heading', {name: 'Test request complete.'}).boundingBox();
    const headerBox = await page.locator('#main-header').boundingBox();
    assert.ok(confirmationBox.y >= headerBox.y + headerBox.height, 'Confirmation heading must clear the fixed header');
    await shot('consultation-demo-confirmation');
    await page.getByRole('button', {name: 'Edit this request'}).click();
    assert.equal(await page.locator('#enquiry-name').inputValue(), 'Synthetic User');
    await page.locator('[name="includeSummary"]').uncheck();
    await page.getByRole('button', {name: 'Review my enquiry'}).click();
    assert.ok(!(await page.locator('#enquiry-draft').inputValue()).includes('Assessment summary'));
    await page.route('**/api/requests', route => route.fulfill({status: 503, contentType: 'application/json', body: JSON.stringify({mode: 'mock', error: 'Demo temporarily unavailable. Try again.'})}));
    await page.getByRole('button', {name: 'Submit test request'}).click();
    await page.getByRole('alert').waitFor();
    assert.match(await page.getByRole('alert').innerText(), /temporarily unavailable/);
    assert.ok(await page.locator('#enquiry-draft').isVisible());
    assert.equal(await page.getByRole('heading', {name: 'Test request complete.'}).count(), 0);
    await shot('submission-retry');
    await page.unroute('**/api/requests');
    await page.getByRole('button', {name: 'Submit test request'}).click();
    await page.getByRole('heading', {name: 'Test request complete.'}).waitFor();
    await page.getByRole('link', {name: 'Refer an organisation', exact: true}).first().click();
    for (const [name, value] of Object.entries({name: 'Synthetic Referrer', email: 'synthetic@example.com', organisation: 'Example One', role: 'Operations', referredOrganisation: 'Example Two', message: 'Synthetic business introduction.'})) await page.locator(`#enquiry-${name}`).fill(value);
    await page.getByRole('button', {name: 'Review my referral'}).click();
    assert.ok(!(await page.locator('#enquiry-draft').count()));
    await page.locator('[name="permission"]').check();
    await page.locator('[name="safeInformation"]').check();
    await page.locator('[name="contactPermission"]').check();
    await shot('referral-form');
    await page.getByRole('button', {name: 'Review my referral'}).click();
    assert.match(await page.locator('#enquiry-draft').inputValue(), /Referred organisation: Example Two/);
    assert.ok(!(await page.locator('#enquiry-draft').inputValue()).includes('Assessment summary'));
    await page.getByRole('button', {name: 'Submit test request'}).click();
    await page.getByRole('heading', {name: 'Test request complete.'}).waitFor();
    assert.match(await page.locator('.lm-demo-receipt').innerText(), /referral passed the demo/);
    await shot('referral-demo-confirmation');
    await page.goto(origin + '/resources/' + ids[1]);
    await page.locator('#lm-sector').selectOption('Allied health practice');
    await page.locator('#lm-system').selectOption('Existing care or practice system');
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    await choices({owner: 'No', next: 'Yes', due: 'Unsure', waiting: 'Yes', exception: 'No', decision: 'Yes'});
    await page.getByRole('button', {name: 'See my result'}).click();
    assert.equal(await page.locator('.lm-result-stat').innerText(), '3 of 6 visibility checks need attention');
    assert.match(await page.locator('.lm-stage-map').innerText(), /New referral \/ enquiry/);
    await shot('intake-result');
    await page.goto(origin + '/resources/' + ids[2]);
    await page.locator('#lm-task').selectOption('Preparing process checklists');
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    await choices({approved: 'Yes', personal: 'No', stakes: 'No'});
    await page.getByRole('button', {name: 'Continue', exact: true}).click();
    await page.getByRole('button', {name: 'See my result'}).click();
    assert.equal(await page.locator('.lm-result').count(), 0);
    await choices({reviewer: 'Yes', checks: 'Unsure', escalation: 'Yes'});
    await page.getByRole('button', {name: 'See my result'}).click();
    assert.ok(await page.getByRole('heading', {name: 'Resolve these conditions first'}).isVisible());
    await shot('ai-result');
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    await context.close();
  }
  assert.equal(posts.length, 8, 'Three successful demo submissions and one simulated failure per viewport');
  assert.ok(posts.every(url => url === origin + '/api/requests'), 'No external provider submissions');
  assert.deepEqual(errors, [], 'Browser runtime or CSP errors');
  console.log('PASS: desktop/mobile assessment flows, required fields, overrides, downloads, context handoff, opt-out, consultation/referral drafts, permission, mock submissions, retry recovery, no browser storage, and no runtime errors.');
  console.log(`Screenshots: ${output}`);
} finally {await browser.close();}
